"""Claude Code のプロンプトに打つ固定キーワードと、日付コマンド（11/5 休み）・事後報告（昨日休んだ）の正規表現。
入力の語彙だけを置く。判定は hook / commands 側。"""
from __future__ import annotations

import re


KW_YASUMI = {"今日休む", "休む"}


KW_UNDO = {"やっぱ出る"}


KW_OKITA = {"起きた", "おきた", "起きたよ", "おきたよ", "起きたわ", "おきたわ", "おはよう", "おはよ", "起床"}


KW_KITAKU = {"ただいま", "帰宅", "帰った", "かえった", "おうちついた", "家ついた"}


KW_UNDO_FUZZY = {"今のなし", "いまのなし", "とりけし", "取り消し", "取消"}


KW_NERU = {"ねる", "寝る", "ねるわ", "寝るわ", "ねます", "寝ます", "ねよ", "寝よ", "おやすみ", "おやすみなさい", "就寝"}


KW_STATUS = {"閉店", "状況"}


KW_SCHEDULE = {"予定", "シフト"}


KW_SHUPPATSU = {"出発", "出発した", "出発する", "行ってきます", "いってきます", "行ってくる", "いってくる",
                "行ってきまーす", "いってきまーす"}


# 「11/5 休み」「明日 出勤」「11/5 戻す」→ 例外日の登録
RE_DAY = re.compile(r"^\s*(\d{1,2}[/／]\d{1,2}|\d{4}-\d{2}-\d{2}|今日|明日)\s*(?:は)?\s*(休み|休む|出勤|出る|戻す)(?:\s+(.*))?$")


# 「休んだ」「昨日休んだ」「11/2 出た」→ 終わった乗務の事後報告
PAST_YASUMI = {"休んだ", "休んでた", "休みました", "休んでました"}


PAST_WORKED = {"出た", "出てた", "出勤した", "行った"}


# 「今日休む 有給」「休む（有休）」→ 当日欠勤を有給で記録（当日欠勤の目安に数えない）
RE_YASUMI_PAID = re.compile(r"^\s*(今日休む|休む)\s*[（(]?\s*(有給|有休)\s*[）)]?\s*$")


# 「11/3 有給」「今日 有給」「11/3 有給なし」→ 休みの記録に有給の印を付ける／外す（日付は必須。『有給』だけやと普通の文）
RE_PAID = re.compile(r"^\s*(\d{1,2}[/／]\d{1,2}|\d{4}-\d{2}-\d{2}|今日|昨日|きのう|一昨日|おととい)\s*(?:は|の休みは|の休み)?\s*"
                     r"(有給|有休)\s*(なし|無し|取消|取り消し|とりけし)?\s*$")


PAID_ON = {"有給", "有休"}                                   # メモ・引数で「有給の印を付ける」
PAID_OFF = {"有給なし", "有休なし", "有給無し", "有休無し"}   # 「外す」


# 「shl neru 23:30」「shl okita 11/7 7時半」→ 後から足す睡眠の記録の時刻（全角は半角にしてから照合する。範囲の確認は呼ぶ側）
RE_CLOCK = re.compile(r"^(\d{1,2})(?::(\d{2})|時(?:(\d{1,2})分?|(半))?)$")


SLEEP_CLEAR = {"取消", "取り消し", "とりけし", "消す", "clear", "rm"}   # 末尾に付けると、その時刻の睡眠の記録を消す


RE_PAST = re.compile(r"^\s*(\d{1,2}[/／]\d{1,2}|\d{4}-\d{2}-\d{2}|今日|昨日|きのう|一昨日|おととい)?\s*(?:は|の乗務は|の乗務)?\s*"
                     r"(休んだ|休んでた|休みました|休んでました|出た|出てた|出勤した|行った)(?:\s+(.*))?$")
